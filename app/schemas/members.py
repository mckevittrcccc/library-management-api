"""Request and response schemas for the Member resource."""

import re

from pydantic import BaseModel, ConfigDict, EmailStr, Field, field_validator

# Documented phone validation rule: NNN-NNN-NNNN (area code, exchange, and
# line number separated by hyphens). Any other format is rejected.
PHONE_PATTERN = re.compile(r"^\d{3}-\d{3}-\d{4}$")


class MemberBase(BaseModel):
    """Define fields shared by every Member schema."""

    # FastAPI uses these type hints and Field constraints in two ways:
    # 1. Pydantic validates request and response data at runtime.
    # 2. FastAPI adds the types and constraints to the OpenAPI document,
    #    which Swagger UI displays as API documentation.
    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
        frozen=True,
    )

    name: str = Field(
        min_length=1,
        max_length=120,
        description="The member's full name.",
        examples=["Jordan Lee"],
    )
    email: EmailStr = Field(
        description="The member's email address; must be unique within the running application.",
        examples=["jordan.lee@example.com"],
    )
    membership_id: str = Field(
        min_length=1,
        max_length=40,
        description="The library-issued membership identifier; must be unique within the running application.",
        examples=["MBR-1001"],
    )
    phone: str = Field(
        description=(
            "The member's phone number. Validation rule: must match "
            "NNN-NNN-NNNN (area code, exchange, and line number separated by hyphens)."
        ),
        examples=["555-201-3048"],
    )

    @field_validator("phone")
    @classmethod
    def validate_phone(cls, value: str) -> str:
        """Enforce the documented NNN-NNN-NNNN phone format."""
        if not PHONE_PATTERN.match(value):
            raise ValueError(
                "phone must match the format NNN-NNN-NNNN, e.g. 555-201-3048"
            )
        return value


class MemberInput(MemberBase):
    """Validate client-controlled fields for a Member create or replacement."""


class MemberResponse(MemberBase):
    """Describe a Member returned by the API."""

    # Pydantic can read values from SQLAlchemy model attributes, not only from
    # dictionaries. FastAPI uses this when it converts ORM objects to JSON.
    model_config = ConfigDict(from_attributes=True)

    # The server generates the ID, so it appears in responses but not in
    # MemberInput request bodies.
    id: int = Field(
        gt=0,
        description="The unique identifier generated by the server.",
        examples=[1],
    )
