"""Request and response schemas for the Book resource."""

from datetime import date

from pydantic import BaseModel, ConfigDict, Field


class BookBase(BaseModel):
    """Define fields shared by every Book schema."""

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
        frozen=True,
    )

    title: str = Field(
        min_length=1,
        max_length=200,
        description="The book's title.",
        examples=["The Pragmatic Programmer"],
    )
    author: str = Field(
        min_length=1,
        max_length=120,
        description="The book's author.",
        examples=["David Thomas"],
    )
    isbn: str = Field(
        min_length=1,
        max_length=20,
        description="The book's ISBN; must be unique within the running application.",
        examples=["978-0135957059"],
    )
    published_year: int = Field(
        ge=1450,
        le=date.today().year,
        description="The year the book was published, between 1450 and the current year.",
        examples=[2019],
    )
    member_id: int = Field(
        gt=0,
        description="The identifier of the Member who currently has this book checked out.",
        examples=[1],
    )


class BookInput(BookBase):
    """Validate client-controlled fields for a Book create or replacement."""


class BookResponse(BookBase):
    """Describe a Book returned by the API."""

    # Pydantic can read values from SQLAlchemy model attributes, not only from
    # dictionaries. FastAPI uses this when it converts ORM objects to JSON.
    model_config = ConfigDict(from_attributes=True)

    id: int = Field(
        gt=0,
        description="The unique identifier generated by the server.",
        examples=[1],
    )
